/**
 * npm run i18n:sync [-- --baseline] [-- --set <name>]
 *
 * For every content set × active language: translate keys that are missing or whose
 * English changed since they were translated, drop keys English removed, and record the
 * English hash in i18n-manifest.json. Resumable: the manifest is written after each batch.
 * --baseline records hashes for keys that are already translated (no API calls) — run once
 * when adopting the sync on existing, reviewed translations.
 */
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'

import { fnv1a } from '../../lib/i18nHash'
import { diffSet, readLocaleFile, writeLocaleFile, type Manifest } from './core'
import { MANIFEST_PATH, readManifest } from './check'
import { SETS, activeLanguages } from './sets'
import { translateBatch } from './translate'

const args = process.argv.slice(2)
const BASELINE = args.includes('--baseline')
const ONLY = args.includes('--set') ? args[args.indexOf('--set') + 1] : undefined
const MAX_KEYS = 60
const MAX_CHARS = 24000

function sortedManifest(m: Manifest): Manifest {
  const out: Manifest = {}
  for (const s of Object.keys(m).sort()) {
    out[s] = {}
    for (const l of Object.keys(m[s]).sort()) {
      out[s][l] = Object.fromEntries(Object.keys(m[s][l]).sort().map((k) => [k, m[s][l][k]]))
    }
  }
  return out
}

function save(m: Manifest) {
  writeFileSync(MANIFEST_PATH, JSON.stringify(sortedManifest(m), null, 1) + '\n')
}

function batches(keys: string[], english: Record<string, string>): string[][] {
  const out: string[][] = []
  let cur: string[] = []
  let chars = 0
  for (const k of keys) {
    const len = english[k].length
    if (cur.length && (cur.length >= MAX_KEYS || chars + len > MAX_CHARS)) { out.push(cur); cur = []; chars = 0 }
    cur.push(k); chars += len
  }
  if (cur.length) out.push(cur)
  return out
}

/** key → English hash for birth-guide keys translated in every active language (app freshness check). */
function writeBirthGuideHashes(m: Manifest) {
  const set = SETS.find((s) => s.name === 'birthGuide')!
  const english = set.english()
  const langs = activeLanguages()
  const lines = Object.keys(english).sort()
    .filter((k) => langs.every((l) => m.birthGuide?.[l]?.[k] === fnv1a(english[k])))
    .map((k) => `  ${JSON.stringify(k)}: '${fnv1a(english[k])}',`)
  writeFileSync(
    join(__dirname, '../../lib/birthGuideContent/hashes.ts'),
    `// Generated by npm run i18n:sync — English hash each bundled translation was made from.\n// A topic edited in the command center no longer matches, so the app won't show a stale translation.\nexport const BIRTH_GUIDE_HASHES: Record<string, string> = {\n${lines.join('\n')}\n}\n`,
  )
}

async function main() {
  const manifest = readManifest()
  for (const set of SETS) {
    if (ONLY && set.name !== ONLY) continue
    const english = set.english()
    for (const lang of activeLanguages()) {
      const path = set.localePath(lang)
      const locale = readLocaleFile(path)
      manifest[set.name] ??= {}
      const done = (manifest[set.name][lang] ??= {})
      if (BASELINE) {
        for (const k of Object.keys(english)) if (k in locale && !(k in done)) done[k] = fnv1a(english[k])
        save(manifest)
        continue
      }
      const { todo, removed } = diffSet(english, locale, done)
      if (removed.length) {
        writeLocaleFile(path, {}, removed)
        for (const k of removed) delete done[k]
        save(manifest)
      }
      if (!todo.length) continue
      console.log(`${set.name}/${lang}: translating ${todo.length} key(s)`)
      for (const keys of batches(todo, english)) {
        const out = await translateBatch(lang, Object.fromEntries(keys.map((k) => [k, english[k]])))
        writeLocaleFile(path, out, [])
        for (const k of keys) done[k] = fnv1a(english[k])
        save(manifest)
        process.stdout.write('.')
      }
      process.stdout.write('\n')
    }
  }
  writeBirthGuideHashes(manifest)
  console.log('Done.')
}

main().catch((e) => { console.error(e instanceof Error ? e.message : e); process.exit(1) })
